/* ─────────────────────────── Writers ─────────────────────────── */

async function emit(outDir: string, rel: string, content: string): Promise<void> {
  const target = join(outDir, rel);
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, content, 'utf8');
}

/**
 * Write the full admin tree (nav, SDK entry, dashboard, and list/create/edit
 * pages) for every model under `options.outDir`.
 */
export async function generateAdminPages(
  models: ModelDefinition[],
  options: { outDir: string },
): Promise<void> {
  const { outDir } = options;
  await emit(outDir, 'lib/admin-nav.ts', renderNav(models));
  await emit(outDir, 'lib/ship.ts', renderShip(models));
  await emit(outDir, 'app/admin/page.tsx', renderDashboard());
  for (const model of models) {
    const base = `app/admin/${model.collection}`;
    await emit(outDir, `${base}/page.tsx`, renderList(model));
    await emit(outDir, `${base}/new/page.tsx`, renderCreate(model));
    await emit(outDir, `${base}/[id]/page.tsx`, renderEdit(model));
  }
}

/* ─────────────────────────── CLI entry ─────────────────────────── */

/** Dynamically load `<cwd>/ship.config.ts` and return its `models`. */
export async function loadModels(cwd: string): Promise<ModelDefinition[]> {
  const configUrl = pathToFileURL(join(cwd, 'ship.config.ts')).href;
  // Dynamic import: the project config path is only known at runtime (`cwd`).
  const mod = (await import(configUrl)) as {
    default?: { models?: ModelDefinition[] };
  };
  return mod.default?.models ?? [];
}

/**
 * Run `ship generate` inside a generated project: load its config and emit the
 * admin tree under `apps/web/src`, logging each written file's relative path.
 */
export async function runGenerate(cwd: string = process.cwd()): Promise<void> {
  const models = await loadModels(cwd);
  await generateAdminPages(models, { outDir: join(cwd, 'apps/web/src') });
  const files = planGeneratePages(models);
  console.log(`${success('Generated')} ${files.length} files:`);
  for (const rel of files) {
    console.log(`  ${info('✓')} ${rel}`);
  }
}
